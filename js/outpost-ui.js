function isInsideStation(x, z) {
  if (x * x + z * z <= 6.2 * 6.2) return true;
  for (let i = 0; i < MODULES_CONFIG.length; i++) {
    const mod = MODULES_CONFIG[i];
    const dx = x - mod.x;
    const dz = z - mod.z;
    if (dx * dx + dz * dz <= 5.2 * 5.2) return true;

    const lenSq = mod.x * mod.x + mod.z * mod.z;
    const t = Math.max(0, Math.min(1, (x * mod.x + z * mod.z) / lenSq));
    const cx = t * mod.x;
    const cz = t * mod.z;
    const cdx = x - cx;
    const cdz = z - cz;
    if (cdx * cdx + cdz * cdz <= 2.2 * 2.2) return true;
  }
  return false;
}

